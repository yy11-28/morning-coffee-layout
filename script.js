const highlightCodeBlock = (codeEl) => {
  if (!codeEl || codeEl.dataset.highlighted === 'true') return;

  const source = codeEl.textContent || '';
  const pattern = /(\/\*[\s\S]*?\*\/|\/\/.*|#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)|[.#]?[A-Za-z_-][\w-]*(?=\s*\{)|[A-Za-z_-][\w-]*(?=\s*:)|[A-Za-z_-][\w-]+|\d+(?:\.\d+)?(?:px|rem|em|vh|vw|%|deg)?|"[^"]*"|'[^']*'|`[^`]*`|[{}();:,])/g;

  let html = '';
  let cursor = 0;
  let match;

  while ((match = pattern.exec(source)) !== null) {
    const token = match[0];
    const start = match.index;

    if (start > cursor) {
      html += escapeHtml(source.slice(cursor, start));
    }

    const before = source.slice(0, start).trimEnd();
    const after = source.slice(start + token.length).trimStart();
    const isComment = /^\/\*|^\/\//.test(token);
    const isSelector = after.startsWith('{') || /[.#]/.test(token) || (/^[A-Za-z_-][\w-]*$/.test(token) && after.startsWith('{'));
    const isProperty = /^(?:[A-Za-z_-][\w-]*)$/.test(token) && after.startsWith(':');
    const isValue = before.endsWith(':') || /^#/.test(token) || /^\d/.test(token) || /(?:px|rem|em|vh|vw|%|deg)$/.test(token) || /^rgba?\(/.test(token) || /^"|^'|^`/.test(token);

    if (isComment) {
      html += `<span class="token comment">${escapeHtml(token)}</span>`;
    } else if (isSelector) {
      html += `<span class="token selector">${escapeHtml(token)}</span>`;
    } else if (isProperty) {
      html += `<span class="token property">${escapeHtml(token)}</span>`;
    } else if (isValue) {
      html += `<span class="token value">${escapeHtml(token)}</span>`;
    } else if (token === '{' || token === '}' || token === ';' || token === ':' || token === ',' || token === '(' || token === ')') {
      html += `<span class="token punctuation">${escapeHtml(token)}</span>`;
    } else {
      html += escapeHtml(token);
    }

    cursor = start + token.length;
  }

  if (cursor < source.length) {
    html += escapeHtml(source.slice(cursor));
  }

  codeEl.innerHTML = html;
  codeEl.dataset.highlighted = 'true';
};

