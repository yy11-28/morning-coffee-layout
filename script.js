const updateTextflowDemo = () => {
  if (!textflowScene || !textflowElement || !textflowTip) return;

  const type = textflowTypeSelect?.value || 'block';
  const width = Number(textflowWidthRange?.value || 80);
  const height = Number(textflowHeightRange?.value || 48);
  const margin = Number(textflowMarginRange?.value || 8);
  const enableFloat = !!textflowFloatToggle?.checked;

  const labelMap = {
    block: { label: 'div', name: 'div块级元素', className: 'block-demo', blockText: '是', sizeText: '是', marginText: '是' },
    inline: { label: 'span', name: 'span行内元素', className: 'inline-demo', blockText: '否', sizeText: '否', marginText: '否' },
    'inline-block': { label: 'img', name: 'img', className: 'img-demo', blockText: '否', sizeText: '是（基线行为）', marginText: '是（不常用）' }
  };

  const item = labelMap[type] || labelMap.block;
  textflowElement.className = `textflow-demo-element ${item.className}`;
  textflowElement.style.setProperty('--box-margin', `${margin}px`);
  textflowElement.style.setProperty('--box-padding', `${Math.min(18, Math.max(8, height / 3))}px`);

  if (type === 'block') {
    textflowElement.style.display = 'block';
    textflowElement.style.width = `${width}px`;
    textflowElement.style.height = `${height}px`;
    textflowElement.style.margin = '0';
    textflowElement.style.float = 'none';
  } else if (type === 'inline') {
    textflowElement.style.display = 'inline';
    textflowElement.style.width = 'auto';
    textflowElement.style.height = 'auto';
    textflowElement.style.margin = '0';
    textflowElement.style.float = enableFloat ? 'left' : 'none';
    if (enableFloat) {
      textflowElement.style.margin = '0 16px 8px 0';
    }
  } else {
    textflowElement.style.display = 'inline-block';
    textflowElement.style.width = `${Math.max(60, width)}px`;
    textflowElement.style.height = `${Math.max(40, height)}px`;
    textflowElement.style.margin = '0';
    textflowElement.style.float = enableFloat ? 'left' : 'none';
    if (enableFloat) {
      textflowElement.style.margin = '0 16px 8px 0';
    }
  }

  const labelHtml = '<span class="box-model-layer margin-layer"></span><span class="box-model-layer padding-layer"></span><span class="box-model-layer content-layer"><span class="demo-box-text">' + item.name + '</span></span>';
  textflowElement.innerHTML = labelHtml;

  if (textflowWidthValue) textflowWidthValue.textContent = `${width}px`;
  if (textflowHeightValue) textflowHeightValue.textContent = `${height}px`;
  if (textflowMarginValue) textflowMarginValue.textContent = `${margin}px`;

  textflowScene?.classList.toggle('float-active', enableFloat);

  if (obsType) obsType.textContent = item.label;
  if (obsBlock) obsBlock.textContent = item.blockText;
  if (obsSize) obsSize.textContent = item.sizeText;
  if (obsMargin) obsMargin.textContent = item.marginText;
  if (obsFloat) obsFloat.textContent = enableFloat ? '有（环绕/塌陷）' : type === 'inline-block' ? '基线问题' : '无';

  if (type === 'block') {
    textflowTip.textContent = `提示：当前是 ${item.label} 元素，在默认文本流下的行为：独占一行，宽度会自动撑满父容器；拖动宽高和 margin 滑块，盒子尺寸和间距都会实时变化。`;
    textflowTip.classList.remove('warning');
  } else if (type === 'inline') {
    textflowTip.classList.add('warning');
    textflowTip.innerHTML = '⚠️ 观察：行内元素设置 width / height 后，尺寸没有变化；设置上下 margin 后，间距也没有变化。';
  } else {
    textflowTip.classList.remove('warning');
    textflowTip.textContent = `提示：当前是 ${item.label} 元素，默认按行内块处理，和文字基线对齐，图片底部会出现缝隙；开启 float 后文字会环绕并脱离正常文档流。`;
    if (enableFloat) {
      textflowTip.textContent += ' 另外，浮动开启后，外层父容器边框会高亮，说明父容器高度塌陷现象已出现。';
    }
  }
};

