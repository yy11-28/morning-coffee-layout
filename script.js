const updatePositionDemo = () => {
  if (!positionMode || !positionTop || !positionLeft || !positionZ || !positionParentToggle || !positionDemoParent || !positionDemoBox || !positionDemoCover) return;

  const mode = positionMode.value;
  const top = Number(positionTop.value);
  const left = Number(positionLeft.value);
  const zIndex = Number(positionZ.value);
  const parentRelative = positionParentToggle.checked;

  positionDemoParent.classList.toggle('is-relative', parentRelative);
  positionDemoParent.classList.toggle('is-not-relative', !parentRelative);

  positionDemoBox.classList.remove('mode-static', 'mode-relative', 'mode-absolute', 'mode-fixed');
  positionDemoBox.classList.add(`mode-${mode}`);

  if (mode === 'static') {
    positionDemoBox.style.top = 'auto';
    positionDemoBox.style.left = 'auto';
    positionDemoBox.style.zIndex = '1';
  } else {
    positionDemoBox.style.top = `${top}px`;
    positionDemoBox.style.left = `${left}px`;
    positionDemoBox.style.zIndex = String(zIndex);
  }

  positionDemoCover.style.zIndex = String(Math.max(1, zIndex - 1));
  positionTopValue.textContent = `${top}px`;
  positionLeftValue.textContent = `${left}px`;
  positionZValue.textContent = String(zIndex);

  if (mode === 'static') {
    positionTip.textContent = 'static 时，元素保持正常文档流，top/left 不生效，不能单独漂浮。';
  } else if (mode === 'relative') {
    positionTip.textContent = 'relative：相对自身原位置做偏移，原占位空间保留，因此其他元素不会被“挤走”。';
  } else if (mode === 'absolute') {
    const ref = parentRelative ? '最近一个非 static 的祖先（父级容器）' : '浏览器视口';
    positionTip.textContent = `absolute：元素脱离文档流，参照物是 ${ref}。若父级是 relative，就会在父容器中自由定位。`;
  } else {
    positionTip.textContent = 'fixed：元素相对视口定位，页面滚动时依然固定，适合悬浮工具栏和弹窗。';
  }

  const parentText = parentRelative ? 'parent { position: relative; }' : 'parent { position: static; }';
  positionCssOutput.textContent = `position: ${mode}; top: ${top}px; left: ${left}px; z-index: ${zIndex}; ${parentText}`;
};

